import numpy as np
from scipy import stats

# Вариант 2
N = np.array([831, 956, 1063, 1204, 1110, 1503, 1053, 1357, 1163, 987])
R = np.array([1349, 1527, 1378, 1681, 1437, 1491, 1413, 1543, 1443, 1487, 1418, 1609, 1473, 1484])

print("Вариант данных №2")


print("Вариационный ряд N:", N)
print("Вариационный ряд R:", R)

print("\nПроверка гипотезы о нормальном распределении:")

shapiro_N = stats.shapiro(N)
print(f"Критерий Шапиро-Уилка для N: W = {shapiro_N.statistic:.4f}, p-value = {shapiro_N.pvalue:.4f}")

shapiro_R = stats.shapiro(R)
print(f"Критерий Шапиро-Уилка для R: W = {shapiro_R.statistic:.4f}, p-value = {shapiro_R.pvalue:.4f}")

if shapiro_N.pvalue > 0.05:
    print("Нулевая гипотеза о нормальности распределения N не отвергается.")
else:
    print("Нулевая гипотеза о нормальности распределения N отвергается.")

if shapiro_R.pvalue > 0.05:
    print("Нулевая гипотеза о нормальности распределения R не отвергается.")
else:
    print("Нулевая гипотеза о нормальности распределения R отвергается.")


print("\nПроверка гипотезы о принадлежности генеральным совокупностям крайних членов вариационных рядов:")

if shapiro_N.pvalue > 0.05:
    G_N_min = (np.abs(N - np.mean(N)) / np.std(N, ddof=1)).max()
    critical_G_N = stats.t.ppf(1 - 0.05 / (2 * len(N)), len(N) - 2) * np.sqrt((len(N) - 1) / (len(N) - 2 + stats.t.ppf(1 - 0.05 / (2 * len(N)), len(N) - 2)**2))
    print(f"Критерий Граббса для N: G = {G_N_min:.4f}, критическое значение = {critical_G_N:.4f}")
    if G_N_min > critical_G_N:
        print("Нулевая гипотеза о принадлежности крайних членов N генеральной совокупности отвергается.")
    else:
        print("Нулевая гипотеза о принадлежности крайних членов N генеральной совокупности не отвергается.")
else:
    print("Невозможно применить критерий Граббса для N, так как распределение не является нормальным.")

if shapiro_R.pvalue > 0.05:
    G_R_min = (np.abs(R - np.mean(R)) / np.std(R, ddof=1)).max()
    critical_G_R = stats.t.ppf(1 - 0.05 / (2 * len(R)), len(R) - 2) * np.sqrt((len(R) - 1) / (len(R) - 2 + stats.t.ppf(1 - 0.05 / (2 * len(R)), len(R) - 2)**2))
    print(f"Критерий Граббса для R: G = {G_R_min:.4f}, критическое значение = {critical_G_R:.4f}")
    if G_R_min > critical_G_R:
        print("Нулевая гипотеза о принадлежности крайних членов R генеральной совокупности отвергается.")
    else:
        print("Нулевая гипотеза о принадлежности крайних членов R генеральной совокупности не отвергается.")
else:
    print("Невозможно применить критерий Граббса для R, так как распределение не является нормальным.") 
    
