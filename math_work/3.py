import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import pearsonr, linregress
from datetime import datetime, timedelta

def load_data(file_path, date_column, value_column, date_format):

    data = pd.read_csv(file_path, delimiter=';')
    data[date_column] = pd.to_datetime(data[date_column], format=date_format)
    return data[date_column].values, data[value_column].values

def compute_correlation_and_regression(dates1, values1, dates2, values2, max_shift):

    best_lag = 0
    best_corr = -1
    best_slope = 0
    best_intercept = 0
    best_dates1 = None
    best_values1 = None
    best_values2 = None

    for lag in range(max_shift + 1):

        dates2_dt = [pd.Timestamp(date).to_pydatetime() for date in dates2]


        shifted_dates2 = [date + timedelta(days=lag * 30) for date in dates2_dt]


        shifted_dates2 = np.array(shifted_dates2, dtype='datetime64[D]')


        min_len = min(len(values1), len(values2))
        s1 = values1[:min_len]
        s2 = values2[:min_len]

        if len(s1) < 2 or len(s2) < 2:
            continue


        s1_norm = (s1 - np.min(s1)) / (np.max(s1) - np.min(s1))
        s2_norm = (s2 - np.min(s2)) / (np.max(s2) - np.min(s2))


        corr, _ = pearsonr(s1_norm, s2_norm)

        if corr > best_corr:
            best_corr = corr
            best_lag = lag
            best_dates1 = dates1
            best_values1 = s1
            best_values2 = s2_norm
            slope, intercept, _, _, _ = linregress(best_values1, best_values2)
            best_slope = slope
            best_intercept = intercept


        print(f"\nСдвиг: {lag} месяц(а)")
        print(f"Вариационный ряд 1 (сдвиг {lag}): {s1_norm}")
        print(f"Вариационный ряд 2 (сдвиг {lag}): {s2_norm}")
        print(f"Коэффициент корреляции: {corr:.4f}")

    return best_lag, best_corr, best_slope, best_intercept, best_dates1, best_values1, best_values2

def plot_and_save(best_dates, best_values1, best_values2, best_slope, best_intercept, file_path):

    plt.figure(figsize=(10, 6))
    plt.scatter(best_dates, best_values1, label='Значения 1', color='blue')
    plt.plot(best_dates, best_slope * best_values1 + best_intercept, color='red', label='Линия регрессии')
    plt.xlabel('Дата')
    plt.ylabel('Значение')
    plt.title('График и линия регрессии')
    plt.legend()
    plt.xticks(rotation=45)
    plt.tight_layout()
    plt.savefig(file_path, dpi=300)
    plt.show()

def main():

    date_format = '%d.%m.%Y'
    dates1, values1 = load_data('urals_oil_rus_export_prices.csv', 'Date', 'Value', date_format)
    dates2, values2 = load_data('dizel_fuel_rus_prices.csv', 'Date', 'Value', date_format)


    max_shift = min(len(values1), len(values2)) // 2


    best_lag, best_corr, best_slope, best_intercept, best_dates, best_values1, best_values2 = compute_correlation_and_regression(dates1, values1, dates2, values2, max_shift)


    print(f"\nЛиния регрессии: y = {best_slope:.4f} * x + {best_intercept:.4f}")

    plot_and_save(best_dates, best_values1, best_values2, best_slope, best_intercept, 'regression_plot.png')

if __name__ == "__main__":
    main() 
    
    
    
