import numpy as np
import pandas as pd
from scipy.stats import pearsonr

def normalize(arr):

    min_val = np.min(arr)
    max_val = np.max(arr)
    range_val = max_val - min_val
    if range_val == 0:
        return arr
    return (arr - min_val) / range_val

def compute_correlation(series1, series2, max_lag):

    correlations = {}
    for lag in range(max_lag + 1):
        if lag > 0:
            s1 = series1[:-lag]
            s2 = series2[lag:]
        else:
            s1 = series1
            s2 = series2


        min_len = min(len(s1), len(s2))
        s1 = s1[:min_len]
        s2 = s2[:min_len]

        if len(s1) < 2 or len(s2) < 2:
            correlations[lag] = np.nan
            continue

        s1_norm = normalize(s1)
        s2_norm = normalize(s2)

        try:
            corr, _ = pearsonr(s1_norm, s2_norm)
            correlations[lag] = corr
        except ValueError as e:
            print(f"Ошибка при расчете корреляции для сдвига {lag}: {e}")
            correlations[lag] = np.nan


        print(f"\nСдвиг: {lag} год(а)")
        print(f"Вариационный ряд 1 (сдвиг {lag}): {s1_norm}")
        print(f"Вариационный ряд 2 (сдвиг {lag}): {s2_norm}")
        print(f"Коэффициент корреляции: {correlations[lag]:.4f}")

    return correlations

def main():

    science_data = pd.read_csv('science_investetions.csv', delimiter=';')
    malignancy_data = pd.read_csv('early_malignancy.csv', delimiter=';')


    science_years = science_data['Year'].values
    science_values = science_data['Value'].values
    malignancy_years = malignancy_data['Year'].values
    malignancy_values = malignancy_data['Value'].values


    max_shift = min(len(science_values), len(malignancy_values)) - 1


    correlations = compute_correlation(science_values, malignancy_values, max_shift)


    max_corr_lag = max(correlations, key=lambda k: correlations[k] if not np.isnan(correlations[k]) else -np.inf)
    print(f"\nМаксимальный коэффициент корреляции {correlations[max_corr_lag]:.4f} при сдвиге {max_corr_lag} год(а)")

if __name__ == "__main__":
    main() 
    
    
